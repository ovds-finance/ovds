-- ── Vendor Ledger ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS `vendor_ledger` (
  `id`                    VARCHAR(36)   NOT NULL,
  `companyId`             VARCHAR(36)   NULL,
  `vendorId`              VARCHAR(36)   NOT NULL,
  `vendorName`            VARCHAR(200)  NOT NULL,
  `entryType`             VARCHAR(30)   NOT NULL DEFAULT 'BILL',
  `reference`             VARCHAR(100)  NULL,
  `description`           VARCHAR(500)  NULL,
  `debit`                 DECIMAL(18,2) NOT NULL DEFAULT 0,
  `credit`                DECIMAL(18,2) NOT NULL DEFAULT 0,
  `balance`               DECIMAL(18,2) NOT NULL DEFAULT 0,
  `currencyCode`          VARCHAR(3)    NOT NULL DEFAULT 'ETB',
  `currencyRate`          DECIMAL(10,4) NOT NULL DEFAULT 1.0000,
  `linkedBillId`           VARCHAR(36)   NULL,
  `linkedPaymentId`       VARCHAR(36)   NULL,
  `linkedJournalEntryId`  VARCHAR(36)   NULL,
  `entryDate`             DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `createdBy`             VARCHAR(100)  NULL,
  `createdAt`             DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt`             DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `vendor_ledger_companyId_idx`  (`companyId`),
  INDEX `vendor_ledger_vendorId_idx`   (`vendorId`),
  INDEX `vendor_ledger_entryDate_idx`  (`entryDate`),
  INDEX `vendor_ledger_comp_ven_idx`   (`companyId`, `vendorId`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

