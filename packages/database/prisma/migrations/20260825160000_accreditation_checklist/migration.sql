-- Create accreditation_checklist table (Sales Registration Systems - Directive No. 1142/2026)
CREATE TABLE IF NOT EXISTS accreditation_checklist (
  id                    VARCHAR(36)   NOT NULL PRIMARY KEY,
  companyId             VARCHAR(36)   NOT NULL,
  title                 VARCHAR(200)  NOT NULL,
  status                VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
  dateOfAdmission       DATETIME      NULL,
  dateOfReport          DATETIME      NULL,
  softwareType          VARCHAR(100)  NULL,
  softwareName          VARCHAR(200)  NULL,
  softwareVersion       VARCHAR(100)  NULL,
  providerContactName   VARCHAR(200)  NULL,
  providerCompanyName   VARCHAR(200)  NULL,
  providerPosition      VARCHAR(100)  NULL,
  providerAddress       TEXT          NULL,
  providerMobile        VARCHAR(20)   NULL,
  providerTelephone     VARCHAR(20)   NULL,
  providerFax           VARCHAR(20)   NULL,
  providerEmail         VARCHAR(200)  NULL,
  ownerLegalName        VARCHAR(200)  NULL,
  ownerAddress          TEXT          NULL,
  ownerCity             VARCHAR(100)  NULL,
  ownerCountry          VARCHAR(100)  NULL,
  ownerTelephone        VARCHAR(20)   NULL,
  ownerContactName      VARCHAR(200)  NULL,
  ownerWebEmail         VARCHAR(200)  NULL,
  strengths             TEXT          NULL,
  nonConformities       TEXT          NULL,
  observations          TEXT          NULL,
  finalDecision         VARCHAR(50)   NULL,
  conditionDetails      TEXT          NULL,
  signatures            TEXT          NULL,
  createdAt             DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt             DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_ac_company (companyId),
  INDEX idx_ac_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Create accreditation_item table
CREATE TABLE IF NOT EXISTS accreditation_item (
  id           VARCHAR(36)   NOT NULL PRIMARY KEY,
  checklistId  VARCHAR(36)   NOT NULL,
  sectionKey   VARCHAR(50)   NOT NULL,
  itemKey      VARCHAR(50)   NOT NULL,
  itemText     TEXT          NOT NULL,
  status       VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
  comment      TEXT          NULL,
  evidence     TEXT          NULL,
  createdAt    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_ai_checklist (checklistId),
  INDEX idx_ai_section (sectionKey),
  INDEX idx_ai_status (status),
  CONSTRAINT fk_ai_checklist FOREIGN KEY (checklistId) REFERENCES accreditation_checklist(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
