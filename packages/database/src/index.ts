// -- Common query helpers -------------------------------------------------------

/**
 * Standard pagination parameters used in findMany queries.
 *
 * Usage:
 *   await prisma.invoice.findMany({
 *     ...paginateQuery(page, limit),
 *     where: { companyId },
 *   });
 */
export function paginateQuery(page = 1, limit = 20): { skip: number; take: number } {
  const take = Math.min(Math.max(1, limit), 200);
  const skip = (Math.max(1, page) - 1) * take;
  return { skip, take };
}

/**
 * Build a standard pagination metadata object from a total count.
 *
 * Usage:
 *   const total = await prisma.invoice.count({ where });
 *   const items = await prisma.invoice.findMany({ ...paginateQuery(page, limit), where });
 *   return { items, pagination: paginationMeta(total, page, limit) };
 */
export function paginationMeta(
  total: number,
  page:  number,
  limit: number,
): { total: number; page: number; limit: number; pages: number; hasNext: boolean; hasPrev: boolean } {
  const pages   = Math.ceil(total / limit) || 1;
  return {
    total,
    page,
    limit,
    pages,
    hasNext: page < pages,
    hasPrev: page > 1,
  };
}

/**
 * Build a PaginatedResponse<T> meta object from a total count.
 * Uses pageSize/totalPages/hasNextPage/hasPrevPage field names to match PaginatedResponse<T>.
 *
 * Usage:
 *   const [items, total] = await Promise.all([
 *     prisma.vatInputLedger.findMany({ ...paginateQuery(page, pageSize), where }),
 *     prisma.vatInputLedger.count({ where }),
 *   ]);
 *   return { data: items, meta: buildMeta(total, page, pageSize) };
 */
export function buildMeta(
  total: number,
  page: number,
  pageSize: number,
): { total: number; page: number; pageSize: number; totalPages: number; hasNextPage: boolean; hasPrevPage: boolean } {
  const totalPages = Math.ceil(total / pageSize) || 1;
  return {
    total,
    page,
    pageSize,
    totalPages,
    hasNextPage: page < totalPages,
    hasPrevPage: page > 1,
  };
}

/**
 * Build a Prisma `orderBy` clause from a sort key and direction.
 * Supports nested keys using dot notation: "department.name"
 *
 * Usage:
 *   orderByClause('department.name', 'asc')
 *   // → { department: { name: 'asc' } }
 */
export function orderByClause(
  key: string,
  direction: 'asc' | 'desc' = 'asc',
): Record<string, any> {
  const parts = key.split('.');
  if (parts.length === 1) return { [key]: direction };
  // Nest from right to left
  return parts.reduceRight<Record<string, any>>(
    (acc, part) => ({ [part]: acc }),
    direction as any,
  );
}

/**
 * Build a Prisma `contains` filter for search fields.
 *
 * Note: mode: 'insensitive' is PostgreSQL-only and not supported by MariaDB/MySQL.
 * Case-insensitivity is handled by the utf8mb4_general_ci collation at the column level.
 *
 * Usage:
 *   const where = searchFilter(['name', 'tin', 'email'], 'acme');
 *   // → { OR: [{ name: { contains: 'acme' } }, ...] }
 */
export function searchFilter(
  fields: string[],
  query:  string,
): { OR: Array<Record<string, any>> } | Record<string, never> {
  if (!query?.trim()) return {};
  const term = query.trim();
  return {
    OR: fields.map(field => ({
      [field]: { contains: term },
    })),
  };
}

/**
 * Build a Prisma `where` clause for a date range on a given field.
 *
 * Usage:
 *   dateRangeFilter('createdAt', '2026-01-01', '2026-03-31')
 *   // → { createdAt: { gte: Date('2026-01-01'), lte: Date('2026-03-31') } }
 */
export function dateRangeFilter(
  field:    string,
  dateFrom: string | Date | undefined,
  dateTo:   string | Date | undefined,
): Record<string, any> {
  if (!dateFrom && !dateTo) return {};
  const filter: Record<string, any> = {};
  if (dateFrom) filter['gte'] = new Date(dateFrom);
  if (dateTo)   filter['lte'] = new Date(new Date(dateTo).setHours(23, 59, 59, 999));
  return { [field]: filter };
}

/**
 * Build a composite `where` clause merging multiple filter objects.
 * Undefined / empty-object filters are skipped.
 *
 * Usage:
 *   const where = mergeFilters(
 *     { companyId },
 *     searchFilter(['name'], search),
 *     dateRangeFilter('createdAt', dateFrom, dateTo),
 *     status ? { status } : {},
 *   );
 */
export function mergeFilters(...filters: Record<string, any>[]): Record<string, any> {
  return Object.assign({}, ...filters.filter(f => Object.keys(f).length > 0));
}
