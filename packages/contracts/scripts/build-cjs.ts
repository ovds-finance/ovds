import { transformFileSync } from '@swc/core';
import * as fs from 'fs';
import * as path from 'path';
import * as crypto from 'crypto';

const srcDir = path.resolve('src');
const cjsOutDir = './dist-cjs';
const esmOutDir = './dist';

// ── Content-hash cache (persisted as JSON next to this script) ────────────────
// Skips SWC re-compilation when source hasn't changed since last build.
const CACHE_FILE = path.join(cjsOutDir, '.build-cache.json');

function loadCache(): Record<string, string> {
  try { return JSON.parse(fs.readFileSync(CACHE_FILE, 'utf8')); } catch { return {}; }
}
function saveCache(cache: Record<string, string>) {
  fs.mkdirSync(path.dirname(CACHE_FILE), { recursive: true });
  fs.writeFileSync(CACHE_FILE, JSON.stringify(cache, null, 2));
}
function fileHash(filePath: string): string {
  return crypto.createHash('md5').update(fs.readFileSync(filePath)).digest('hex');
}

function walkDir(dir: string): string[] {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkDir(fullPath));
    } else if (entry.name.endsWith('.ts')) {
      files.push(fullPath);
    }
  }
  return files;
}

const cache = loadCache();
let compiled = 0;
let skipped = 0;

// ── Step 1: CJS + ESM build for all src files (SWC, cache-aware) ─────────────
const files = walkDir(srcDir);

for (const fullPath of files) {
  const normalised = fullPath.replace(/\\/g, '/');
  const srcPrefix = srcDir.replace(/\\/g, '/') + '/';
  const relativePath = normalised.replace(new RegExp(`^${srcPrefix}`), '');
  const hash = fileHash(fullPath);
  const cjsOut = path.join(cjsOutDir, relativePath.replace('.ts', '.js'));
  const esmOut = path.join(esmOutDir, relativePath.replace('.ts', '.js'));

  // Skip if hash unchanged AND both outputs exist
  const cacheKey = `src/${relativePath}`;
  if (
    cache[cacheKey] === hash &&
    fs.existsSync(cjsOut) &&
    fs.existsSync(esmOut)
  ) {
    skipped++;
    continue;
  }

  fs.mkdirSync(path.dirname(cjsOut), { recursive: true });
  fs.mkdirSync(path.dirname(esmOut), { recursive: true });

  // CJS
  const cjsResult = transformFileSync(fullPath, {
    jsc: { parser: { syntax: 'typescript' }, target: 'es2020' },
    module: { type: 'commonjs', strictMode: true },
    sourceMaps: false,
  });
  fs.writeFileSync(cjsOut, cjsResult.code);

  // ESM — only needed for prisma-zod; the rest comes from tsc's outDir
  // but we write it anyway so the cache key covers both outputs cleanly.
  const esmResult = transformFileSync(fullPath, {
    jsc: { parser: { syntax: 'typescript' }, target: 'es2020' },
    module: { type: 'es6', strictMode: true },
    sourceMaps: false,
  });
  fs.writeFileSync(esmOut, esmResult.code);

  cache[cacheKey] = hash;
  compiled++;
}

saveCache(cache);
console.log(`[1/3] CJS+ESM: ${compiled} compiled, ${skipped} skipped (unchanged)`);

// ── Step 2: prisma-zod .d.ts stub (points IDEs back to source) ───────────────
const prismaSrc    = path.join(srcDir, 'prisma-zod', 'index.ts');
const prismaDtsOut = path.join(esmOutDir, 'prisma-zod', 'index.d.ts');
const prismaDtsMapOut = path.join(esmOutDir, 'prisma-zod', 'index.d.ts.map');

if (fs.existsSync(prismaSrc)) {
  fs.mkdirSync(path.dirname(prismaDtsOut), { recursive: true });
  const stub = `// Auto-generated by build-cjs.ts\nexport * from '../../src/prisma-zod/index';\n`;
  const existing = fs.existsSync(prismaDtsOut) ? fs.readFileSync(prismaDtsOut, 'utf8') : '';
  if (existing !== stub) fs.writeFileSync(prismaDtsOut, stub);
  if (fs.existsSync(prismaDtsMapOut)) fs.unlinkSync(prismaDtsMapOut);
  console.log(`[2/3] prisma-zod .d.ts stub written`);
} else {
  console.log(`[2/3] prisma-zod source not found — skipped`);
}

// ── Step 3: Patch dist/index.js and dist-cjs/index.js ────────────────────────
// src/index.ts omits the prisma-zod re-export (keeps tsc fast).
// We append it to the compiled outputs here so consumers importing from
// '@ovds/contracts' still get all prisma-zod exports transparently.

const MARKER = 'Auto-injected by build-cjs.ts';
const patches: Array<[string, string]> = [
  [
    path.join(esmOutDir, 'index.js'),
    `\n// ${MARKER}\nexport * from './prisma-zod/index.js';\n`,
  ],
  [
    path.join(cjsOutDir, 'index.js'),
    `\n// ${MARKER}\nconst _pz = require('./prisma-zod/index.js'); Object.assign(exports, _pz);\n`,
  ],
  [
    path.join(esmOutDir, 'index.d.ts'),
    `\n// ${MARKER}\nexport * from './prisma-zod/index';\n`,
  ],
];

for (const [filePath, append] of patches) {
  if (!fs.existsSync(filePath)) continue;
  const content = fs.readFileSync(filePath, 'utf8');
  if (!content.includes(MARKER)) fs.appendFileSync(filePath, append);
}

console.log(`[3/3] Patched dist/index.js, dist-cjs/index.js, dist/index.d.ts`);
