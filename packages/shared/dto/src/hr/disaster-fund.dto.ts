import {
  IsString,
  IsNumber,
  IsOptional,
  IsArray,
  IsBoolean,
  IsEnum,
  IsInt,
  Min,
  Max,
  MaxLength,
  ArrayMinSize,
  ArrayMaxSize,
} from 'class-validator';
import { Type } from 'class-transformer';
import { ContributionCategory, ContributionStatus } from '@ovds/shared/types';

export class CreateContributionDto {
  @IsEnum(ContributionCategory)
  category: ContributionCategory;

  @IsOptional()
  @IsString()
  @MaxLength(500)
  description?: string;

  @Type(() => Number)
  @IsNumber()
  @Min(0)
  baseAmount: number;

  @IsString()
  @MaxLength(20)
  period: string;

  @IsOptional()
  @IsString()
  dueDate?: string;

  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;
}

export class UpdateContributionDto {
  @IsOptional()
  @IsEnum(ContributionStatus)
  status?: ContributionStatus;

  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;

  @IsOptional()
  @IsString()
  remittedAt?: string;
}

export class BatchCalculateItemDto {
  @IsString()
  @MaxLength(100)
  category: string;

  @Type(() => Number)
  @IsNumber()
  @Min(0)
  baseAmount: number;

  @IsOptional()
  @IsString()
  @MaxLength(200)
  label?: string;
}

export class BatchCalculateDto {
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(100)
  @Type(() => BatchCalculateItemDto)
  items: BatchCalculateItemDto[];
}

export class UpsertLevyTargetDto {
  @Type(() => Number)
  @IsInt()
  @Min(2000)
  @Max(2100)
  year: number;

  @IsString()
  @MaxLength(100)
  category: string;

  @Type(() => Number)
  @IsNumber()
  @Min(0)
  targetAmount: number;

  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;
}

export class RecordRemittanceDto {
  @Type(() => Number)
  @IsNumber()
  @Min(0.01)
  amount: number;

  @IsOptional()
  @IsString()
  @MaxLength(200)
  bankName?: string;

  @IsOptional()
  @IsString()
  @MaxLength(100)
  referenceNo?: string;

  @IsOptional()
  @IsString()
  remittedAt?: string;

  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;
}

export class AutoGenerateDto {
  @IsString()
  @MaxLength(20)
  period: string;

  @IsArray()
  @ArrayMinSize(1)
  @IsString({ each: true })
  sources: string[];

  @IsOptional()
  @IsBoolean()
  dryRun?: boolean;

  @IsOptional()
  @IsString()
  @MaxLength(100)
  businessType?: string;
}

export class SaveDisasterFundReportDto {
  @IsString()
  @MaxLength(300)
  title: string;

  @IsOptional()
  @IsString()
  @MaxLength(20)
  period?: string;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(2000)
  @Max(2100)
  year?: number;

  @IsOptional()
  @IsString()
  @MaxLength(50)
  status?: string;
}

export class SubmitToErcaDto {
  @IsString()
  @MaxLength(20)
  period: string;

  @IsString()
  @MaxLength(100)
  paymentMethod: string;

  @IsOptional()
  @IsString()
  @MaxLength(200)
  bankName?: string;

  @IsOptional()
  @IsString()
  @MaxLength(100)
  paymentReference?: string;

  @IsOptional()
  @IsString()
  @MaxLength(100)
  ercaReferenceNo?: string;

  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;
}
