export function getWebAppSecuritySummary() {
  const total = WEB_APP_SECURITY_CHECKLIST.length;
  const implemented = WEB_APP_SECURITY_CHECKLIST.filter((i) => i.implemented).length;
  return {
    total,
    implemented,
    pending: total - implemented,
    readinessScore: Math.round((implemented / total) * 100),
  };
}
